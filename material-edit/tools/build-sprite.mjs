// Rebuilds the inline Lucide icon sprite inside src/index.html (ISC licensed icons, https://lucide.dev).
// Usage:  npm i --no-save lucide-static  &&  node tools/build-sprite.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lucide = process.argv[2] || join(root, 'node_modules', 'lucide-static', 'icons');

// sprite id -> Lucide icon name
const MAP = {
  menu: 'menu', undo: 'undo-2', redo: 'redo-2', play: 'play', pause: 'pause', first: 'skip-back', last: 'skip-forward',
  back: 'chevron-left', fwd: 'chevron-right', split: 'square-split-horizontal', trash: 'trash-2', copy: 'copy', plus: 'plus',
  minus: 'minus', check: 'check', close: 'x', text: 'type', film: 'film', wand: 'wand-sparkles', swap: 'arrow-left-right',
  music: 'music', image: 'image', layers: 'layers', vol: 'volume-2', mute: 'volume-x', export: 'upload', magnet: 'magnet',
  fit: 'unfold-horizontal', fullscreen: 'maximize', open: 'folder-open', new: 'file-plus', save: 'save', tune: 'sliders-horizontal',
  sun: 'sun', moon: 'moon', auto: 'monitor', link: 'link', rotate: 'rotate-ccw', info: 'info', gear: 'settings', home: 'house',
  grid: 'layout-grid', list: 'list', search: 'search', more: 'ellipsis-vertical', shrink: 'minimize', edit: 'pencil',
  keyboard: 'keyboard', paste: 'clipboard', cut: 'scissors', repeat: 'repeat', camera: 'camera', bolt: 'zap',
  sort: 'arrow-down-wide-narrow', 'cloud-check': 'circle-check', 'play-fill': 'play', video: 'video',
  // settings dialog
  palette: 'palette', globe: 'languages', font: 'a-large-small', window: 'app-window', folder: 'folder', gauge: 'gauge', chip: 'cpu',
  heart: 'heart', reset: 'rotate-ccw', layout: 'panels-top-left', sparkles: 'sparkles',
};
const FILLED = new Set(['play', 'play-fill']);

const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '')
  .replace(/\s+/g, ' ').replace(/ \/>/g, '/>').trim();

const symbols = Object.entries(MAP).map(([id, name]) => {
  let body = inner(readFileSync(join(lucide, name + '.svg'), 'utf8'));
  if (FILLED.has(id)) body = body.replace(/<(polygon|path)/g, '<$1 fill="currentColor"');
  return `    <symbol id="i-${id}" viewBox="0 0 24 24">${body}</symbol>`;
}).join('\n');

const file = join(root, 'src', 'index.html');
let html = readFileSync(file, 'utf8');
const block = `<!-- lucide:start (generated by tools/build-sprite.mjs · Lucide icons, ISC) -->\n  <svg width="0" height="0" style="position:absolute" aria-hidden="true">\n${symbols}\n  </svg>\n  <!-- lucide:end -->`;
if (html.includes('<!-- lucide:start')) html = html.replace(/<!-- lucide:start[\s\S]*?<!-- lucide:end -->/, block);
else html = html.replace(/<svg width="0" height="0"[\s\S]*?<\/svg>/, block);
writeFileSync(file, html);
console.log(`Sprite written: ${Object.keys(MAP).length} icons`);
