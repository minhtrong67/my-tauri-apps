// Copies only the latin, latin-ext and vietnamese subsets of the bundled fonts and writes app/src/styles/fonts.css.
// Run with: node tools/fonts/make-fonts.mjs  (needs the @fontsource packages from npm install)
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '../..');
const nm = path.join(root, 'node_modules');
const outDir = path.join(root, 'app/src/assets/fonts');
const SUBS = ['latin', 'latin-ext', 'vietnamese'];
fs.mkdirSync(outDir, { recursive: true });
let css = '/* Generated by tools/fonts/make-fonts.mjs. Subsets: latin, latin-ext, vietnamese. All fonts are under the SIL OFL licence. */\n';

// variable fonts: take the blocks of wght.css
const variable = [
  ['@fontsource-variable/roboto', 'roboto', 'Roboto'],
  ['@fontsource-variable/inter', 'inter', 'Inter'],
];
for (const [pkg, slug, family] of variable) {
  const text = fs.readFileSync(path.join(nm, pkg, 'wght.css'), 'utf8');
  for (const block of text.split('/* ').slice(1)) {
    const name = block.slice(0, block.indexOf(' */')).trim();       // e.g. inter-latin-wght-normal
    const sub = SUBS.find((s) => name === `${slug}-${s}-wght-normal`);
    if (!sub) continue;
    const file = `${name}.woff2`;
    fs.copyFileSync(path.join(nm, pkg, 'files', file), path.join(outDir, file));
    const range = block.match(/unicode-range:([^;]+);/)[1].trim();
    const wt = block.match(/font-weight:\s*([^;]+);/)[1].trim();
    css += `@font-face{font-family:'${family}';font-style:normal;font-display:swap;font-weight:${wt};src:url(../assets/fonts/${file}) format('woff2');unicode-range:${range}}\n`;
  }
}
// Be Vietnam Pro: static weights
const be = '@fontsource/be-vietnam-pro';
const beCss = fs.readFileSync(path.join(nm, be, '400.css'), 'utf8');
const ranges = {};
for (const block of beCss.split('/* ').slice(1)) {
  const name = block.slice(0, block.indexOf(' */')).trim();
  const sub = SUBS.find((s) => name === `be-vietnam-pro-${s}-400-normal`);
  if (sub) ranges[sub] = block.match(/unicode-range:([^;]+);/)[1].trim();
}
for (const w of [400, 500, 600, 700]) for (const sub of SUBS) {
  const file = `be-vietnam-pro-${sub}-${w}-normal.woff2`;
  fs.copyFileSync(path.join(nm, be, 'files', file), path.join(outDir, file));
  css += `@font-face{font-family:'Be Vietnam Pro';font-style:normal;font-display:swap;font-weight:${w};src:url(../assets/fonts/${file}) format('woff2');unicode-range:${ranges[sub]}}\n`;
}
fs.writeFileSync(path.join(root, 'app/src/styles/fonts.css'), css);
console.log('fonts ready:', fs.readdirSync(outDir).length, 'files');
