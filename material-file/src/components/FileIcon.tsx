import { memo, useEffect, useState } from 'react';
import { AppWindow, File, FileArchive, FileAudio, FileCode2, FileImage, FileSpreadsheet, FileText, FileVideo, Folder, Presentation, type LucideIcon } from 'lucide-react';
import type { Entry } from '../lib/types';
import { catOf, isRaster, isSvg } from '../lib/fileTypes';
import { api, convertFileSrc } from '../lib/api';

const ICONS: Record<string, LucideIcon> = {
  image: FileImage, video: FileVideo, audio: FileAudio, archive: FileArchive, doc: FileText, sheet: FileSpreadsheet,
  slide: Presentation, code: FileCode2, exe: AppWindow, text: FileText, file: File
};
export const FileIcon = memo(function FileIcon({ entry, size = 20, className = '' }: { entry: Pick<Entry, 'name' | 'isDir'>; size?: number; className?: string }) {
  const cat = catOf(entry);
  if (cat === 'folder') return <Folder size={size} className={className} style={{ color: 'var(--folder)', fill: 'color-mix(in oklab, var(--folder) 85%, transparent)' }} strokeWidth={1.6} />;
  const I = ICONS[cat] || File;
  return <I size={size} className={className} style={{ color: `var(--k-${cat})` }} strokeWidth={1.8} />;
});

/* thumbnails are generated by Rust and cached on disk; limit concurrency so scrolling stays smooth */
const cache = new Map<string, string | null>();
const queue: (() => void)[] = []; let running = 0;
const pump = () => { while (running < 3 && queue.length) { running++; queue.shift()!(); } };
function requestThumb(path: string, key: string, size: number): Promise<string | null> {
  if (cache.has(key)) return Promise.resolve(cache.get(key)!);
  return new Promise((resolve) => {
    queue.push(() => {
      api.getThumbnail(path, size).then((p) => convertFileSrc(p)).catch(() => null).then((r) => { cache.set(key, r); resolve(r); }).finally(() => { running--; pump(); });
    });
    pump();
  });
}
/** Image thumbnail with graceful fallback to the file-type icon. */
export const Thumb = memo(function Thumb({ entry, size, iconSize, big, enabled }: { entry: Entry; size: number; iconSize: number; big?: boolean; enabled: boolean }) {
  const raster = enabled && isRaster(entry) && entry.size < 64 * 1024 * 1024;
  const svg = enabled && isSvg(entry) && entry.size < 4 * 1024 * 1024;
  const key = `${entry.path}|${entry.modified}|${size}`;
  const [src, setSrc] = useState<string | null>(() => cache.get(key) ?? null);
  const [bad, setBad] = useState(false);
  useEffect(() => {
    let live = true; setBad(false);
    if (svg) { setSrc(convertFileSrc(entry.path)); return; }
    if (!raster) { setSrc(null); return; }
    const hit = cache.get(key);
    if (hit !== undefined) { setSrc(hit); return; }
    setSrc(null);
    void requestThumb(entry.path, key, size).then((r) => { if (live) setSrc(r || (big ? convertFileSrc(entry.path) : null)); });
    return () => { live = false; };
  }, [entry.path, key, raster, svg, size, big]);
  if (src && !bad) return <img src={src} alt="" loading="lazy" decoding="async" draggable={false} onError={() => setBad(true)} className="size-full animate-[fade-in_.3s] rounded-[inherit] object-cover" />;
  return <FileIcon entry={entry} size={iconSize} />;
});
