// Rebuilds the inline icon sprite inside src/index.html from Microsoft's Fluent System Icons (MIT, https://github.com/microsoft/fluentui-system-icons).
// Usage:  pnpm add -D @fluentui/svg-icons  &&  pnpm sprite
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = process.argv[2] || join(root, 'node_modules', '@fluentui', 'svg-icons', 'icons');

// sprite id -> [Fluent icon name, 'regular' | 'filled']
const R = 'regular', F = 'filled';
const MAP = {
  menu: ['line_horizontal_3', R], undo: ['arrow_undo', R], redo: ['arrow_redo', R], play: ['play', F], pause: ['pause', F], first: ['previous', F], last: ['next', F],
  back: ['chevron_left', R], fwd: ['chevron_right', R], split: ['filmstrip_split', R], trash: ['delete', R], copy: ['copy', R], plus: ['add', R], minus: ['subtract', R],
  check: ['checkmark', R], close: ['dismiss', R], text: ['text_t', R], film: ['video_clip', R], wand: ['wand', R], swap: ['arrow_swap', R], music: ['music_note_2', R],
  image: ['image', R], layers: ['layer', R], vol: ['speaker_2', R], mute: ['speaker_mute', R], export: ['arrow_export', R], fit: ['zoom_fit', R], fullscreen: ['full_screen_maximize', R],
  open: ['folder_open', R], new: ['document_add', R], save: ['save', R], tune: ['options', R], sun: ['weather_sunny', R], moon: ['weather_moon', R], auto: ['desktop', R],
  link: ['link', R], rotate: ['arrow_counterclockwise', R], info: ['info', R], gear: ['settings', R], home: ['home', R], grid: ['grid', R], list: ['text_bullet_list', R],
  search: ['search', R], more: ['more_vertical', R], shrink: ['full_screen_minimize', R], edit: ['edit', R], keyboard: ['keyboard', R], paste: ['clipboard_paste', R], cut: ['cut', R],
  repeat: ['arrow_repeat_all', R], camera: ['camera', R], bolt: ['flash', R], sort: ['arrow_sort', R], 'cloud-check': ['checkmark_circle', R], 'play-fill': ['play', F], video: ['video', R],
  palette: ['color', R], globe: ['globe', R], font: ['text_font', R], window: ['window', R], folder: ['folder', R], gauge: ['top_speed', R], chip: ['developer_board', R], heart: ['heart', R],
  reset: ['arrow_counterclockwise', R], layout: ['grid', R], sparkles: ['sparkle', R], alert: ['warning', R], error: ['error_circle', R], command: ['keyboard', R], chev: ['chevron_down', R],
  enter: ['arrow_enter_left', R], up: ['arrow_up', R], diamond: ['diamond', R], 'diamond-fill': ['diamond', F], crop: ['crop', R], flag: ['flag', F], mic: ['mic', R],
  captions: ['closed_caption', R], snowflake: ['weather_snowflake', R], square: ['square', F],
};
// Fluent has no magnet glyph: a hand-drawn one in the same 24px filled style (used for "snap").
const CUSTOM = {
  magnet: '<path d="M5 3h4v3H5zM15 3h4v3h-4z"/><path d="M5 7.5h4V11a3 3 0 0 0 6 0V7.5h4V11a7 7 0 0 1-14 0z"/>',
};

const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s+fill="[^"]*"/g, '').replace(/\s+/g, ' ').replace(/ \/>/g, '/>').trim();
const sym = (id, body) => `    <symbol id="i-${id}" viewBox="0 0 24 24">${body}</symbol>`;
const symbols = [
  ...Object.entries(MAP).map(([id, [name, v]]) => sym(id, inner(readFileSync(join(dir, `${name}_24_${v}.svg`), 'utf8')))),
  ...Object.entries(CUSTOM).map(([id, body]) => sym(id, body)),
].join('\n');

const file = join(root, 'src', 'index.html');
let html = readFileSync(file, 'utf8');
const block = `<!-- icons:start (generated by tools/build-sprite.mjs · Fluent System Icons, MIT) -->\n  <svg width="0" height="0" style="position:absolute" aria-hidden="true">\n${symbols}\n  </svg>\n  <!-- icons:end -->`;
html = html.replace(/<!-- (?:lucide|icons):start[\s\S]*?<!-- (?:lucide|icons):end -->/, block);
writeFileSync(file, html);
console.log(`Sprite written: ${Object.keys(MAP).length + Object.keys(CUSTOM).length} icons`);
