export const dict: Record<Lang, Record<Key, string>> = { vi, en };

export function systemLang(): Lang {
  const l = (typeof navigator !== "undefined" ? navigator.languages?.[0] ?? navigator.language : "en") ?? "en";
  return l.toLowerCase().startsWith("vi") ? "vi" : "en";
}
export function resolveLang(pref: LangPref): Lang {
  return pref === "system" ? systemLang() : pref;
}
export function locale(lang: Lang): string {
  return lang === "vi" ? "vi-VN" : "en-GB"; // en-GB => giờ 24h
}

export type TFn = (key: Key, params?: Record<string, string | number>) => string;
export function makeT(lang: Lang): TFn {
  const d = dict[lang];
  return (key, params) => {
    let s = d[key] ?? key;
    if (params) for (const k in params) s = s.split(`{${k}}`).join(String(params[k]));
    return s;
  };
}

const Ctx = createContext<{ lang: Lang; t: TFn }>({ lang: "vi", t: makeT("vi") });
export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  // makeT nhẹ; value đổi khi đổi ngôn ngữ -> cả cây render lại một lần
  return <Ctx.Provider value={{ lang, t: makeT(lang) }}>{children}</Ctx.Provider>;
}
export const useI18n = () => useContext(Ctx);

/** Chuỗi có **đậm** và `code` -> JSX */
export function rich(s: string): ReactNode {
  return s.split(/(\*\*[^*]+\*\*|`[^`]+`)/g).map((p, i) =>
    p.startsWith("**") ? <b key={i}>{p.slice(2, -2)}</b> : p.startsWith("`") ? <code key={i}>{p.slice(1, -1)}</code> : <Fragment key={i}>{p}</Fragment>
  );
}
