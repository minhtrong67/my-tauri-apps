/** Solid Fluent System Icons behind the lucide-style names used across the app (size / className / style work as before; strokeWidth is ignored). */
export interface IconProps { size?: number | string; strokeWidth?: number; className?: string; style?: CSSProperties; fill?: string; color?: string; 'aria-hidden'?: boolean; title?: string }
export type IconType = ComponentType<IconProps>;
export type LucideIcon = IconType;
type Raw = ComponentType<{ className?: string; style?: CSSProperties; 'aria-hidden'?: boolean }>;
function make(C: Raw): IconType {
  return function Icon({ size, strokeWidth: _s, fill: _f, color, className, style, ...rest }: IconProps) {
    const st = size !== undefined || color ? { ...(size !== undefined ? { width: size, height: size } : null), ...(color ? { color } : null), ...style } : style;
    return <C className={className} style={st} aria-hidden {...rest} />;
  };
}

