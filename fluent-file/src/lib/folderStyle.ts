export function onColor(hex: string): string {
  const n = parseInt(hex.replace('#', ''), 16);
  const l = (0.2126 * ((n >> 16) & 255) + 0.7152 * ((n >> 8) & 255) + 0.0722 * (n & 255)) / 255;
  return l > 0.62 ? 'rgba(40,28,0,.78)' : 'rgba(255,255,255,.95)';
}
