// Generates src/fonts.css: bundled UI fonts limited to the latin, latin-ext and vietnamese subsets
// (the two languages the app supports). Run with `npm run fonts` after changing the family list.
import { readFileSync, writeFileSync } from 'node:fs';

const SUBSETS = ['latin', 'latin-ext', 'vietnamese'];
const NM = '../node_modules';

const variable = [
  ['inter', 'Inter Variable'],
  ['open-sans', 'Open Sans Variable'],
  ['noto-sans', 'Noto Sans Variable'],
  ['nunito', 'Nunito Variable'],
  ['montserrat', 'Montserrat Variable'],
  ['source-sans-3', 'Source Sans 3 Variable'],
];
const fixed = [
  ['roboto', 'Roboto', [400, 500, 700]],
  ['be-vietnam-pro', 'Be Vietnam Pro', [400, 500, 700]],
];

let out = '/* AUTO-GENERATED by scripts/gen-fonts.mjs - do not edit by hand */\n';

for (const [pkg, family] of variable) {
  const css = readFileSync(`node_modules/@fontsource-variable/${pkg}/wght.css`, 'utf8');
  for (const block of css.match(/@font-face\s*{[^}]*}/g) ?? []) {
    const m = block.match(/url\(\.\/files\/([^)]+-(latin|latin-ext|vietnamese)-wght-normal\.woff2)\)/);
    if (!m) continue;
    const range = block.match(/unicode-range:[^;]+;/)?.[0] ?? '';
    out += `@font-face{font-family:'${family}';font-style:normal;font-display:swap;font-weight:100 900;src:url(${NM}/@fontsource-variable/${pkg}/files/${m[1]}) format('woff2');${range}}\n`;
  }
}

for (const [pkg, family, weights] of fixed) {
  const uni = JSON.parse(readFileSync(`node_modules/@fontsource/${pkg}/unicode.json`, 'utf8'));
  for (const w of weights) {
    for (const sub of SUBSETS) {
      out += `@font-face{font-family:'${family}';font-style:normal;font-display:swap;font-weight:${w};src:url(${NM}/@fontsource/${pkg}/files/${pkg}-${sub}-${w}-normal.woff2) format('woff2');unicode-range:${uni[sub]};}\n`;
    }
  }
}

writeFileSync('src/fonts.css', out);
console.log('src/fonts.css written,', out.split('\n').length - 2, 'font faces');
