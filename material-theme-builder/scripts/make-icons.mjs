// Generates every icon of the project from the vector artwork in icon-art.mjs:
//   - src-tauri/icons/*  (png set, icon.ico, icon.icns, Windows Store tiles)
//   - src-tauri/icons/setup.ico, uninstall.ico (installer / uninstaller)
//   - src-tauri/windows/header.bmp, sidebar.bmp (NSIS installer artwork)
//   - app/public/favicon.svg and app/src/lib/logo-art.ts (in-app logo)
// Usage: npm run icons
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import pngToIco from "png-to-ico";
import { COOKIE, PALETTE, appInner, appSvg, bannerSvg, setupSvg, uninstallSvg } from "./icon-art.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const icons = join(root, "src-tauri", "icons");
const win = join(root, "src-tauri", "windows");
mkdirSync(icons, { recursive: true });
mkdirSync(win, { recursive: true });

const png = (svg, size) => sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png({ compressionLevel: 9 }).toBuffer();
const out = (name, buf) => writeFileSync(join(icons, name), buf);

const app = appSvg();
const ICO_SIZES = [16, 24, 32, 48, 64, 128, 256];

async function ico(svg) {
  return pngToIco(await Promise.all(ICO_SIZES.map((s) => png(svg, s))));
}

/** Minimal ICNS writer: PNG payloads, which every modern macOS accepts. */
async function icns(svg) {
  const types = [["icp4", 16], ["icp5", 32], ["icp6", 64], ["ic07", 128], ["ic08", 256], ["ic09", 512], ["ic10", 1024], ["ic11", 32], ["ic12", 64], ["ic13", 256], ["ic14", 512]];
  const chunks = [];
  for (const [type, size] of types) {
    const data = await png(svg, size);
    const head = Buffer.alloc(8);
    head.write(type, 0, "ascii");
    head.writeUInt32BE(data.length + 8, 4);
    chunks.push(head, data);
  }
  const body = Buffer.concat(chunks);
  const head = Buffer.alloc(8);
  head.write("icns", 0, "ascii");
  head.writeUInt32BE(body.length + 8, 4);
  return Buffer.concat([head, body]);
}

/** 24-bit BMP (what NSIS expects for header / sidebar images). */
async function bmp(svg, w, h) {
  const { data } = await sharp(Buffer.from(svg)).resize(w, h).flatten({ background: PALETTE.violet.deep }).raw().toBuffer({ resolveWithObject: true });
  const ch = data.length / (w * h);
  const rowSize = Math.ceil((w * 3) / 4) * 4;
  const pixels = Buffer.alloc(rowSize * h);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const s = (y * w + x) * ch;
      const d = (h - 1 - y) * rowSize + x * 3;
      pixels[d] = data[s + 2];
      pixels[d + 1] = data[s + 1];
      pixels[d + 2] = data[s];
    }
  }
  const header = Buffer.alloc(54);
  header.write("BM", 0);
  header.writeUInt32LE(54 + pixels.length, 2);
  header.writeUInt32LE(54, 10);
  header.writeUInt32LE(40, 14);
  header.writeInt32LE(w, 18);
  header.writeInt32LE(h, 22);
  header.writeUInt16LE(1, 26);
  header.writeUInt16LE(24, 28);
  header.writeUInt32LE(pixels.length, 34);
  header.writeInt32LE(2835, 38);
  header.writeInt32LE(2835, 42);
  return Buffer.concat([header, pixels]);
}

// Tauri standard set
out("icon.png", await png(app, 1024));
out("32x32.png", await png(app, 32));
out("64x64.png", await png(app, 64));
out("128x128.png", await png(app, 128));
out("128x128@2x.png", await png(app, 256));
out("icon.ico", await ico(app));
out("icon.icns", await icns(app));

// Windows Store / Appx tiles
for (const s of [30, 44, 71, 89, 107, 142, 150, 284, 310]) out(`Square${s}x${s}Logo.png`, await png(app, s));
out("StoreLogo.png", await png(app, 50));

// Installer + uninstaller icons (same family, different glyph + Vibrant-scheme color)
out("setup.ico", await ico(setupSvg()));
out("uninstall.ico", await ico(uninstallSvg()));
out("setup.png", await png(setupSvg(), 256));
out("uninstall.png", await png(uninstallSvg(), 256));

// NSIS artwork: header 150x57, sidebar 164x314
writeFileSync(join(win, "header.bmp"), await bmp(bannerSvg(450, 171), 150, 57));
writeFileSync(join(win, "sidebar.bmp"), await bmp(bannerSvg(492, 942, true), 164, 314));

// In-app logo + favicon
writeFileSync(join(root, "app", "public", "favicon.svg"), app);
writeFileSync(join(root, "app", "public", "icon.png"), await png(app, 256));
writeFileSync(join(root, "app", "src", "lib", "logo-art.ts"), `// Generated by scripts/make-icons.mjs - do not edit.\nexport const COOKIE_PATH = ${JSON.stringify(COOKIE)};\n/** Inner SVG markup of the app icon (viewBox 0 0 1024 1024). Flat colors, so it has no ids to clash. */\nexport const LOGO_INNER = ${JSON.stringify(appInner())};\n`);

console.log("Icons generated in src-tauri/icons, installer art in src-tauri/windows.");
