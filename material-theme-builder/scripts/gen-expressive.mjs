// Generates the Material 3 Expressive motion + shape tokens shared by the app and the landing page.
//  - Spring curves are simulated from the M3 Expressive "MotionScheme" (damping ratio + stiffness)
//    and exported as CSS `linear()` easing functions.
//  - Shapes are polygons with an identical point count so `clip-path` can morph between them.
// Output: app/src/expressive.css and (when markers exist) the <style> block inside ../index.html
// Usage: node scripts/gen-expressive.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/* ------------------------------ springs ------------------------------ */
// Material 3 Expressive motion scheme (damping ratio, stiffness)
const SPRINGS = {
  "spatial-fast": [0.6, 800],
  "spatial": [0.8, 380],
  "spatial-slow": [0.8, 200],
  "effects-fast": [1, 3800],
  "effects": [1, 1600],
  "effects-slow": [1, 800],
};

function simulate(zeta, k) {
  const c = 2 * zeta * Math.sqrt(k);
  const dt = 1 / 1000;
  let x = 0;
  let v = 0;
  const xs = [0];
  let settled = 0;
  for (let i = 1; i < 4000; i++) {
    const a = -k * (x - 1) - c * v;
    v += a * dt;
    x += v * dt;
    xs.push(x);
    if (Math.abs(x - 1) < 0.002 && Math.abs(v) < 0.02) {
      settled = i;
      break;
    }
  }
  return { xs, ms: Math.max(settled, 120) };
}

function linearFn({ xs, ms }, points = 36) {
  const out = [];
  for (let i = 0; i < points; i++) {
    const t = i / (points - 1);
    const idx = Math.min(xs.length - 1, Math.round(t * (xs.length - 1)));
    out.push(+xs[idx].toFixed(4));
  }
  out[out.length - 1] = 1;
  return `linear(${out.join(", ")})`;
}

let css = `/* AUTO-GENERATED by scripts/gen-expressive.mjs - do not edit by hand. */\n`;
css += `:root{\n`;
// graceful fallbacks for engines without linear()
css += `  --spring-spatial-fast: cubic-bezier(.3,1.5,.5,1); --spring-spatial: cubic-bezier(.34,1.35,.5,1); --spring-spatial-slow: cubic-bezier(.3,1.2,.5,1);\n`;
css += `  --spring-effects-fast: cubic-bezier(.2,0,0,1); --spring-effects: cubic-bezier(.2,0,0,1); --spring-effects-slow: cubic-bezier(.2,0,0,1);\n`;
const durs = {};
const fns = {};
for (const [name, [z, k]] of Object.entries(SPRINGS)) {
  const sim = simulate(z, k);
  durs[name] = Math.round(sim.ms / 10) * 10;
  fns[name] = linearFn(sim, name.startsWith("spatial") ? 40 : 24);
  css += `  --spring-${name}-d: ${durs[name]}ms;\n`;
}
css += `}\n`;
css += `@supports (transition-timing-function: linear(0, 1)){\n  :root{\n`;
for (const name of Object.keys(SPRINGS)) css += `    --spring-${name}: ${fns[name]};\n`;
css += `  }\n}\n`;

/* ------------------------------- shapes ------------------------------ */
const N = 48; // points per polygon (must match for morphing)
function polar(fn, rotate = 0) {
  const pts = [];
  let max = 0;
  const raw = [];
  for (let i = 0; i < N; i++) {
    const th = (i / N) * Math.PI * 2 + rotate;
    const r = fn(th);
    raw.push([Math.cos(th - rotate) * r, Math.sin(th - rotate) * r]);
    max = Math.max(max, r);
  }
  for (const [x, y] of raw) pts.push([50 + (x / max) * 50, 50 + (y / max) * 50]);
  return pts;
}
const lobes = (n, a, phase = 0) => (th) => 1 + a * Math.cos(n * th + phase);
const superellipse = (p) => (th) => Math.pow(Math.pow(Math.abs(Math.cos(th)), p) + Math.pow(Math.abs(Math.sin(th)), p), -1 / p);

const SHAPES = {
  circle: polar(() => 1),
  cookie: polar(lobes(9, 0.07)),
  sunny: polar(lobes(8, 0.11)),
  clover: polar(lobes(4, 0.2, Math.PI)),
  flower: polar(lobes(6, 0.15)),
  burst: polar(lobes(12, 0.1)),
  gem: polar(lobes(5, 0.12, Math.PI / 5)),
  squircle: polar(superellipse(4)),
  pebble: polar((th) => 1 + 0.1 * Math.cos(2 * th) + 0.08 * Math.cos(3 * th + 1)),
};
const poly = (pts) => `polygon(${pts.map(([x, y]) => `${x.toFixed(1)}% ${y.toFixed(1)}%`).join(",")})`;

css += `\n/* Shape library: identical point counts so clip-path morphs between any two shapes */\n`;
css += `:root{\n`;
for (const [name, pts] of Object.entries(SHAPES)) css += `  --shape-${name}: ${poly(pts)};\n`;
css += `}\n`;
for (const [name, pts] of Object.entries(SHAPES)) css += `.shape-${name}{clip-path:var(--shape-${name})}\n`;
for (const [name, pts] of Object.entries(SHAPES)) css += `.hover-shape-${name}:hover{clip-path:${poly(pts)}}\n`;
css += `.shape{transition:clip-path var(--spring-spatial-d) var(--spring-spatial)}\n`;

// Loading indicator: cycles through shapes while rotating (M3 Expressive "loading indicator")
const LOOP = ["sunny", "cookie", "clover", "burst", "gem", "flower", "pebble"];
css += `@keyframes shape-loop{\n`;
LOOP.forEach((s, i) => {
  css += `  ${((i / LOOP.length) * 100).toFixed(2)}%{clip-path:${poly(SHAPES[s])}}\n`;
});
css += `  100%{clip-path:${poly(SHAPES[LOOP[0]])}}\n}\n`;
css += `@keyframes shape-loop-slow{\n`;
["cookie", "sunny", "flower", "clover", "cookie"].forEach((s, i, a) => {
  css += `  ${((i / (a.length - 1)) * 100).toFixed(2)}%{clip-path:${poly(SHAPES[s])}}\n`;
});
css += `}\n`;

writeFileSync(join(root, "app/src/expressive.css"), css);
console.log("wrote app/src/expressive.css", css.length, "bytes", durs);

// inject into landing page between markers
try {
  const htmlPath = join(root, "index.html");
  let html = readFileSync(htmlPath, "utf8");
  const a = "/*EXPRESSIVE:START*/";
  const b = "/*EXPRESSIVE:END*/";
  if (html.includes(a) && html.includes(b)) {
    html = html.slice(0, html.indexOf(a) + a.length) + "\n" + css + "\n" + html.slice(html.indexOf(b));
    writeFileSync(htmlPath, html);
    console.log("updated index.html");
  }
} catch {
  /* landing page not present */
}
