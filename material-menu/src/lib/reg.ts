import type { AppState, Entry } from './api'

const PREFIX = 'MaterialMenu.'
const pad3 = (n: number) => String(n).padStart(3, '0')
const safeId = (s: string) => s.replace(/[^A-Za-z0-9]/g, '').slice(0, 16)
const slug = (s: string) => (s.toLowerCase().replace(/[^a-z0-9]/g, '_').slice(0, 24) || 'g')

function bases(e: Entry): string[] {
  const out: string[] = []
  for (const s of e.scopes) {
    if (s === 'files') out.push('*')
    else if (s === 'folders') out.push('Directory')
    else if (s === 'background') out.push('Directory\\Background')
    else if (s === 'drives') out.push('Drive')
    else if (s === 'desktop') out.push('DesktopBackground')
    else if (['image', 'video', 'audio', 'text'].includes(s)) out.push(`SystemFileAssociations\\${s}`)
    else if (s === 'ext') for (const x of e.extensions) { const t = x.trim().replace(/^\./, '').replace(/[^A-Za-z0-9]/g, ''); if (t) out.push(`SystemFileAssociations\\.${t.toLowerCase()}`) }
  }
  return out
}

/** "name"="value" – ASCII as REG_SZ text, anything else as hex(1) UTF-16LE so regedit keeps Unicode intact. */
function str(name: string, value: string) {
  const n = name === '@' ? '@' : `"${name}"`
  if (/^[\x20-\x7e]*$/.test(value)) return `${n}="${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
  const bytes: string[] = []
  for (let i = 0; i < value.length; i++) { const c = value.charCodeAt(i); bytes.push((c & 255).toString(16).padStart(2, '0'), (c >> 8).toString(16).padStart(2, '0')) }
  bytes.push('00', '00')
  return `${n}=hex(1):${bytes.join(',')}`
}

function verb(path: string, e: Entry, lines: string[]) {
  lines.push(`[HKEY_CURRENT_USER\\Software\\Classes\\${path}]`, str('MUIVerb', e.label))
  if (e.icon.trim()) lines.push(str('Icon', e.icon.trim()))
  if (e.position === 'top') lines.push(str('Position', 'Top'))
  if (e.position === 'bottom') lines.push(str('Position', 'Bottom'))
  if (e.shiftOnly) lines.push(str('Extended', ''))
  const flags = (e.separatorBefore ? 0x20 : 0) | (e.separatorAfter ? 0x40 : 0)
  if (flags) lines.push(`"CommandFlags"=dword:${flags.toString(16).padStart(8, '0')}`)
  lines.push('', `[HKEY_CURRENT_USER\\Software\\Classes\\${path}\\command]`, str('@', e.command), '')
}

export function buildReg(state: AppState): string {
  const L: string[] = ['Windows Registry Editor Version 5.00', '', '; Generated by Material Menu', '']
  const all = new Set<string>()
  state.entries.forEach((e) => bases(e).forEach((b) => all.add(b)))
  for (const b of all) {
    const groups = new Set<string>()
    state.entries.forEach((e, idx) => {
      if (!e.enabled || !e.label.trim() || !e.command.trim() || !bases(e).includes(b)) return
      const base = `${b}\\shell`
      const sub = e.submenu.trim()
      if (!sub) return verb(`${base}\\${PREFIX}${pad3(idx)}_${safeId(e.id)}`, e, L)
      const gk = `${base}\\${PREFIX}${pad3(idx)}_g_${slug(sub)}`
      const gslug = slug(sub)
      if (!groups.has(gslug)) {
        groups.add(gslug)
        L.push(`[HKEY_CURRENT_USER\\Software\\Classes\\${gk}]`, str('MUIVerb', sub), str('SubCommands', ''))
        if (e.icon.trim()) L.push(str('Icon', e.icon.trim()))
        L.push('')
      }
      // the group key keeps the index of its first entry
      const first = state.entries.findIndex((x) => x.enabled && x.submenu.trim() && slug(x.submenu) === gslug && bases(x).includes(b))
      verb(`${base}\\${PREFIX}${pad3(first)}_g_${gslug}\\shell\\${pad3(idx)}_${safeId(e.id)}`, e, L)
    })
  }
  for (const h of state.hiddenVerbs) L.push(`[HKEY_CURRENT_USER\\Software\\Classes\\${h.base}\\shell\\${h.name}]`, str('LegacyDisable', ''), str('ProgrammaticAccessOnly', ''), '')
  if (state.blockedClsids.length) {
    L.push('[HKEY_CURRENT_USER\\Software\\Microsoft\\Windows\\CurrentVersion\\Shell Extensions\\Blocked]')
    state.blockedClsids.forEach((c) => L.push(str(c.toUpperCase(), 'Blocked by Material Menu')))
    L.push('')
  }
  if (state.classic) L.push('[HKEY_CURRENT_USER\\Software\\Classes\\CLSID\\{86ca1aa0-34aa-4e8b-a509-50c905bae2a2}\\InprocServer32]', str('@', ''), '')
  return L.join('\r\n')
}
