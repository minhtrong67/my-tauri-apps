export const dictionaries = { en, vi } as const;

export type Vars = Record<string, string | number>;

function translate(lang: "en" | "vi", key: string, vars?: Vars): string {
  let s = dictionaries[lang][key] ?? en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(String(vars[k]));
  return s;
}

/** Non-reactive translate (toasts, dialogs created from actions). */
export const t = (key: string, vars?: Vars) => translate(useSettings.getState().lang, key, vars);

/** Reactive translate for components: re-renders when the language changes. */
export function useT() {
  const lang = useSettings((s) => s.lang);
  return useCallback((key: string, vars?: Vars) => translate(lang, key, vars), [lang]);
}
