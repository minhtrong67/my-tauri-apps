// Exports a handful of Lucide icons as plain SVG strings for the browser extension (no bundler needed there).
import { writeFileSync } from "node:fs";

const names = ["download", "settings", "film", "radio", "check", "trash", "monitor", "sun", "moon", "link-2", "play", "plug-zap", "circle-alert", "globe", "x", "wifi-off", "list-video", "zap", "layers", "palette", "languages", "puzzle", "shield-check", "chevron-down", "menu", "gauge", "pause", "clipboard", "heart"];
const out = {};
for (const n of names) {
  const mod = await import(new URL(`../node_modules/lucide-react/dist/esm/icons/${n}.mjs`, import.meta.url));
  const nodes = mod.__iconData.node;
  out[n] = nodes
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ");
      return `<${tag} ${a}/>`;
    })
    .join("");
}
const js = `// Generated by scripts/build-extension-icons.mjs from lucide-react. Do not edit by hand.
const PATHS = ${JSON.stringify(out, null, 2)};

export function icon(name, size = 20) {
  return \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${PATHS[name] || ""}</svg>\`;
}
`;
writeFileSync(new URL("../extension/lib/icons.js", import.meta.url), js);
console.log("icons.js written:", Object.keys(out).length, "icons");
