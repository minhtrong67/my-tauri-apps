// Generates extension/lib/palettes.js: Material tonal palettes (light + dark) for every theme color.
import { Hct, SchemeTonalSpot, argbFromHex, hexFromArgb } from "@material/material-color-utilities";
import { writeFileSync } from "node:fs";

const SWATCHES = {
  blue: "#769CDF", red: "#F44336", pink: "#E91E63", purple: "#9C27B0", "deep-purple": "#673AB7", indigo: "#3F51B5",
  "light-blue": "#03A9F4", cyan: "#00BCD4", teal: "#009688", green: "#4CAF50", "light-green": "#8BC34A", lime: "#CDDC39",
  amber: "#FFC107", orange: "#FF9800", "deep-orange": "#FF5722", brown: "#795548", "blue-grey": "#607D8B",
};

function vars(seed, dark) {
  const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, 0);
  const h = (p, t) => hexFromArgb(p.tone(t));
  const L = !dark;
  const p = s.primaryPalette, sec = s.secondaryPalette, ter = s.tertiaryPalette, e = s.errorPalette, n = s.neutralPalette, nv = s.neutralVariantPalette;
  return {
    "primary": h(p, L ? 40 : 80), "on-primary": h(p, L ? 100 : 20), "primary-container": h(p, L ? 90 : 30), "on-primary-container": h(p, L ? 10 : 90),
    "secondary": h(sec, L ? 40 : 80), "secondary-container": h(sec, L ? 90 : 30), "on-secondary-container": h(sec, L ? 10 : 90),
    "tertiary": h(ter, L ? 40 : 80), "on-tertiary": h(ter, L ? 100 : 20), "tertiary-container": h(ter, L ? 90 : 30), "on-tertiary-container": h(ter, L ? 10 : 90),
    "error": h(e, L ? 40 : 80), "on-error": h(e, L ? 100 : 20), "error-container": h(e, L ? 90 : 30), "on-error-container": h(e, L ? 10 : 90),
    "surface": h(n, L ? 98 : 6), "on-surface": h(n, L ? 10 : 90), "on-surface-variant": h(nv, L ? 30 : 80),
    "outline": h(nv, L ? 50 : 60), "outline-variant": h(nv, L ? 80 : 30),
    "surface-low": h(n, L ? 96 : 10), "surface-container": h(n, L ? 94 : 12), "surface-high": h(n, L ? 92 : 17), "surface-highest": h(n, L ? 90 : 22),
    "inverse-surface": h(n, L ? 20 : 90), "inverse-on-surface": h(n, L ? 95 : 20), "inverse-primary": h(p, L ? 80 : 40),
  };
}
const out = {};
for (const [id, hex] of Object.entries(SWATCHES)) out[id] = { seed: hex, light: vars(hex, false), dark: vars(hex, true) };
writeFileSync(new URL("../extension/lib/palettes.js", import.meta.url), `// Generated by scripts/build-extension-palettes.mjs. Do not edit by hand.\nexport const PALETTES = ${JSON.stringify(out)};\n`);
console.log("palettes:", Object.keys(out).length);
