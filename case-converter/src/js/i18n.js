/** First preferred device language that we support; Vietnamese devices get Vietnamese, everything else English. */
export function detectLanguage() {
  const prefs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language]) || [];
  for (const l of prefs) {
    const code = String(l || '').toLowerCase();
    if (code.startsWith('vi')) return 'vi';
    if (code.startsWith('en')) return 'en';
  }
  return 'en';
}

let current = 'en';
export const setLanguage = (l) => {
  current = STRINGS[l] ? l : 'en';
  document.documentElement.lang = current;
  return current;
};
export const getLanguage = () => current;
export const t = (key) => STRINGS[current][key] ?? STRINGS.en[key] ?? key;
